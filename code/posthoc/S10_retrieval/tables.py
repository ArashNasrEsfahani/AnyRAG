"""results.json -> tables.md (markdown tables used by RESULTS.md). No model call."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = json.loads((HERE / "results.json").read_text(encoding="utf-8"))
ORDER = ["DENSE_6000", "BM25_6000", "HYBRID_6000", "HR_6000", "LEX5B_6000",
         "DENSE_15500", "BM25_15500", "HYBRID_15500", "HR_15500", "LEX5B_15500"]


def b(x):
    lo, hi = x[0], x[1]
    return "%d" % lo if lo == hi else "%d..%d" % (lo, hi)


md = ["# S10 tables (generated by tables.py from results.json)", "", "## Accuracy /90, abstention /6, size, tokens", "",
      "| arm | correct /90 | unresolved | abstain correct /6 | evidence chars (mean) | answer prompt tokens (mean) | completion tokens (mean) | LLM calls / q |",
      "|---|---|---|---|---|---|---|---|"]
for a in ORDER:
    t = R["table"][a]
    md.append("| %s | %s | %d | %s | %.0f | %s | %s | 1 |" % (
        a, b(t["acc90"]), t["unresolved"], b(t["abstain_correct"]) if t["abstain_correct"] else "-",
        t["evidence_chars_mean"], t["answer_prompt_tokens_mean"], t["answer_completion_tokens_mean"]))

for g, keys in (("tier", None), ("lang", None), ("genre", None), ("pool", None), ("subtype", None)):
    ks = list(R["groups"]["DENSE_6000"][g].keys())
    md += ["", "## by %s (correct, bounds; n in header)" % g, "",
           "| arm | " + " | ".join("%s (n=%d)" % (k, R["groups"]["DENSE_6000"][g][k][2]) for k in ks) + " |",
           "|---|" + "---|" * len(ks)]
    for a in ORDER:
        md.append("| %s | %s |" % (a, " | ".join(b(R["groups"][a][g][k]) for k in ks)))

md += ["", "## Paired comparisons (family of %d; Bonferroni alpha %.4f)" % (R["family_size"], R["bonferroni_alpha"]), "",
       "| comparison | a | b | net (bounds) | a better / b better (resolved) | sign p (range) | 95% CI pp, questions | 95% CI pp, 20 components |",
       "|---|---|---|---|---|---|---|---|"]
for k, c in R["compare"].items():
    lo, hi = c["net_bounds"]
    net = "%+d" % lo if lo == hi else "%+d..%+d" % (lo, hi)
    p0, p1 = c["sign_p_range"]
    p = "%.4f" % p0 if abs(p0 - p1) < 5e-5 else "%.4f-%.4f" % (p0, p1)
    md.append("| %s | %s | %s | %s | %d / %d | %s | [%.1f, %.1f] | [%.1f, %.1f] |" % (
        k, b(c["acc_a"]), b(c["acc_b"]), net, c["better_worse_resolved"][0], c["better_worse_resolved"][1], p,
        *c["ci_pp_question"], *c["ci_pp_component"]))


def rc(d):
    return "%d / %d / %d" % (d.get("complete", 0), d.get("partial", 0), d.get("none", 0))


for name, key in (("delivered pack (S7 t1_reach method: verbatim quote >= 90% in a same-document pack item)", "reach"),
                  ("top-40 candidate list before packing (S7 t5 span method: gold span >= 90% covered by chunk spans)",
                   "list_reach")):
    cols = ["all", "T1", "T2", "T3", "fa", "en", "RPT", "BOOK", "LAW"]
    md += ["", "## Gold-bundle coverage, %s: complete / partial / none" % name, "",
           "| arm | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    for a in ORDER:
        md.append("| %s | %s |" % (a, " | ".join(rc(R[key][a].get(c, {})) for c in cols)))

for bud, w in R["wins"].items():
    md += ["", "## DENSE vs BM25 at %s: resolved discordant questions" % bud, "",
           "dense right & BM25 wrong: %d; BM25 right & dense wrong: %d; both right: %d; both wrong: %d; "
           "either-channel oracle: %d/90" % (w["dense_only"], w["bm25_only"], w["both_right"], w["both_wrong"],
                                              w["oracle_either"]), ""]
    for g in ("tier", "lang", "genre", "subtype"):
        md.append("- by %s (dense-only / bm25-only): %s" % (g, ", ".join("%s %d/%d" % (k, v[0], v[1])
                                                                        for k, v in w["by"][g].items())))
    md += ["", "| question | winner | tier | lang | subtype | HYBRID same budget | pack reach dense / bm25 | gloss |",
           "|---|---|---|---|---|---|---|---|"]
    for r in sorted(w["rows"], key=lambda r: (r["winner"], r["q"])):
        md.append("| %s | %s | %s | %s | %s | %s | %s / %s | %s |" % (
            r["q"], r["winner"], r["tier"], r["lang"], r["subtype"], b(r["hybrid"]), r["reach_dense"], r["reach_bm25"],
            r["gloss"].replace("|", "/")))
(HERE / "tables.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print("\n".join(md))
