"""S14: compact replication table from lang.json (no new statistics) -> compact_table.md"""
import json
from pathlib import Path
H = Path(__file__).resolve().parent
R = json.loads((H / "lang.json").read_text(encoding="utf-8"))
def n(c): lo, hi = c["net_bounds"]; return ("%+d" % lo) if lo == hi else "%+d..%+d" % (lo, hi)
def rng(cs):
    lo = min(c["net_bounds"][0] for c in cs); hi = max(c["net_bounds"][1] for c in cs); return "%+d..%+d" % (lo, hi)
def p(c): a, b = c["sign_p_range"]; return ("%.3f" % a) if abs(a - b) < 5e-4 else "%.3f-%.3f" % (a, b)
md = ["# S14 compact replication table (from lang.json; generated by t3_compact.py)", "",
      "Net A - B per half (fa /45, en /45). Readers = range over the five replay readers (judge 1). Reps = GLM reader",
      "replicates r1; r2. J2 = judge 2 on GLM r0 ('-' = not judged or undetermined). Interaction p = worst-case "
      "component-level permutation p (all 90).", "",
      "| contrast | GLM fa | GLM en | no-contam fa /39 | no-contam en /25 | 5 readers fa | 5 readers en | reps fa (r1; r2) | reps en (r1; r2) | J2 fa | J2 en | interaction p_c |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for name, v in R["contrasts"].items():
    rows = v["rows"]; pr = rows[0]
    rd = [r for r in rows if r["kind"] == "reader"]; rp = [r for r in rows if r["kind"] == "replicate"]
    j2 = [r for r in rows if r["kind"] == "judge2" and not r["all90"].get("undetermined")]
    f = lambda lg: "%s (p %s)" % (n(pr["all90"][lg]), p(pr["all90"][lg]))
    g = lambda lg: "%s (p %s)" % (n(pr["nocontam64"][lg]), p(pr["nocontam64"][lg]))
    md.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
        name, f("fa"), f("en"), g("fa"), g("en"),
        rng([r["all90"]["fa"] for r in rd]) if rd else "-", rng([r["all90"]["en"] for r in rd]) if rd else "-",
        "; ".join(n(r["all90"]["fa"]) for r in rp) or "-", "; ".join(n(r["all90"]["en"]) for r in rp) or "-",
        n(j2[0]["all90"]["fa"]) if j2 else "-", n(j2[0]["all90"]["en"]) if j2 else "-",
        "%.3f" % pr["all90"]["interaction_perm"]["p_component"][1]))
(H / "compact_table.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print("\n".join(md))
