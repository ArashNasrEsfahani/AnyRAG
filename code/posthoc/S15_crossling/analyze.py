# ------------------------------------------------------------------ experiment X retrieval
def tally(exp, cond, arm, qs):
    c = Counter()
    for q in qs:
        r = R[(exp, cond, arm, q)]
        c["rc_" + r["recall40"]["cls"]] += 1
        c["items_hit"] += r["recall40"]["items_hit"]
        c["items"] += r["recall40"]["items"]
        c["reach_" + r["reach"]["cls"]] += 1
    return dict(c)


ARMS_X = ["BM25", "DENSE", "HYB", "HR"]
GROUPS = {"fa": [q for q in ANS if L.lang_of(q) == "fa"], "en": [q for q in ANS if L.lang_of(q) == "en"]}
GROUPS["all"] = ANS
