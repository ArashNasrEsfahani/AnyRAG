_SC = {}


def own_score(arm, q):
    r = ANSW.get((arm, q))
    if r is None:
        return 0, 0
    rid = RID.get((arm, q))
    if rid is None:
        return 0, 1
    v = VD.get((rid, JM.answer_sha1({"answer_text": r["answer_text"]})))
    if v is None or v["status"] == "needs_adjudication":
        return 0, 1
    return v["strict"], v["strict"]


def sc(arm):
    def f(q):
        k = (arm, q)
        if k not in _SC:
            _SC[k] = own_score(arm, q) if arm in ("HR_6000_TRANS", "CLOSEDBOOK_TRANS") else S7.score(arm, q)
        return _SC[k]
    return f


def tot(arm, qs):
    f = sc(arm)
    return sum(f(q)[0] for q in qs), sum(f(q)[1] for q in qs)


