"""Combine crosscheck_freq_results.json and parts/bayes_*.json into crosscheck_results.json and tables.md."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
F = json.loads((HERE / "crosscheck_freq_results.json").read_text())
REFS = ("HYBRID_6000", "HR_6000", "LEX5B_6000", "SETR_6000")
for fill in (0, 1):
    R = F["fits"]["answerable90|unres=%d" % fill]
    for m in ("vb", "map"):
        for lab in ("default", "diffuse"):
            c, s = {}, {}
            for ref in REFS:
                p = HERE / "parts" / ("bayes_%s_%s_unres%d_%s.json" % (m, lab, fill, ref))
                if p.exists():
                    d = json.loads(p.read_text()); c.update(d["contrasts"]); s[ref] = d["sigmas"]
            R["BayesMixedGLM_%s_%s" % (m, lab)] = c
            R["BayesMixedGLM_%s_%s_sigmas" % (m, lab)] = s
(HERE / "crosscheck_results.json").write_text(json.dumps(F, indent=1), encoding="utf-8")

ROWS = ["LEX5B_6000 vs HYBRID_6000", "LEX5B_6000 vs HR_6000", "HR_6000 vs HYBRID_6000", "SETR_6000 vs LEX5B_6000",
        "budget HYBRID (15500-6000)", "budget HR (15500-6000)", "budget LEX5B (15500-6000)", "budget SETR (15500-6000)"]
COLS = [("custom_ML_Laplace", "custom ML-Laplace (q + pack)"),
        ("BayesMixedGLM_vb_diffuse", "statsmodels VB, diffuse priors"), ("BayesMixedGLM_vb_default", "statsmodels VB, default priors"),
        ("BayesMixedGLM_map_diffuse", "statsmodels MAP, diffuse priors"), ("BayesMixedGLM_map_default", "statsmodels MAP, default priors"),
        ("GEE_exch_q", "GEE exch. (robust SE)"), ("GEE_exch_q_biasreduced", "GEE exch. (bias-reduced SE)"),
        ("GLM_cluster_q", "GLM, cluster-robust SE"), ("GLM_naive_iid", "GLM, naive iid SE")]


def cell(v):
    if not v:
        return "n/a"
    lo, hi = v["OR_ci95"]
    return "%+.3f (%.3f); OR %.2f [%.2f, %.2f]; p %.3f" % (v["logOR"], v["se"], v["OR"], lo, hi, v["p"])


out = ["# Cross-check tables (generated by combine.py)", ""]
for key, R in F["fits"].items():
    out += ["## %s (n = %d answers, %d questions, %d packs)" % (key, R["n"], R["n_q"], R["n_pack"]), "",
            "log-odds ratio (SE); OR [95% Wald / posterior-normal interval]; two-sided p (normal). VB/MAP p is the "
            "normal-approximation tail of mean/SD, reported for comparison only.", ""]
    cols = [c for c in COLS if c[0] in R]
    for k in ROWS:
        out.append("**%s**" % k)
        out.append("")
        out.append("| estimator | estimate |")
        out.append("|---|---|")
        for c, lab in cols:
            out.append("| %s | %s |" % (lab, cell(R[c].get(k))))
        out.append("")
    sig = ["custom: sigma_q %.3f, sigma_pack %.3f" % (R["custom_sigmas"]["sigma_question"], R["custom_sigmas"]["sigma_pack"])]
    for c, lab in cols:
        s = R.get(c + "_sigmas")
        if s:
            sig.append("%s: " % lab + "; ".join("%s q %.3f pack %.3f" % (ref.split("_")[0] + " ref", v["sigma_question"], v["sigma_pack"])
                                                for ref, v in s.items()))
    out += ["Variance components: " + " | ".join(sig), "", "GEE working exchangeable correlation: %.3f" % R["GEE_exch_q_working_corr"], "",
            "Interaction (pipeline:reader, 15 df):", ""]
    for k, v in R["interaction"].items():
        out.append("- %s: stat %.2f, df %d, p %.3f%s" % (k, v["stat"], v["df"], v["p"],
                                                       (" (n used %d, groups %d)" % (v["n_used"], v["n_groups_used"])) if "n_used" in v else ""))
    out.append("")
(HERE / "tables.md").write_text("\n".join(out), encoding="utf-8")
print("\n".join(out))
