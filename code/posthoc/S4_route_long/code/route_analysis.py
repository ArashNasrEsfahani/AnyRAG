"""Experiment 1: oracle and real routing, from saved test verdicts and ledgers (no model calls).
Writes S4/routing_results.json and S4/routing_tables.md."""
import json
import common as C
import stats_common as S

TOK = json.loads((C.S4 / "frozen_cell_tokens.json").read_text(encoding="utf-8"))
ARMS = S.RT.ARMS
WIDE = ["HR_15500", "LEX5B_15500", "SETR_15500", "HYBRID_15500"]
CHEAP = "HYBRID_6000"
RQ = {r["id"]: r for r in C.jl(C.S4 / "router_test_v1.jsonl")}
assert len(RQ) == 96
TQ = C.test_questions()
FMT = {q: TQ[q]["answer_format"] for q in TQ}


def policies():
    P = {}
    for a in ARMS:
        P["always " + a] = {"route": (lambda q, a=a: a), "router": None}
    for w in WIDE:
        P["oracle T1->%s, T2/T3->%s" % (CHEAP, w)] = {
            "route": (lambda q, w=w: CHEAP if S.intended_tier(q) == "T1" else w), "router": None}
        P["GLM router v1: T1->%s, else %s" % (CHEAP, w)] = {
            "route": (lambda q, w=w: CHEAP if RQ[q]["pred"] == "T1" else w), "router": "glm"}
        P["format rule (v2_single->T1): %s / %s" % (CHEAP, w)] = {
            "route": (lambda q, w=w: CHEAP if FMT[q] == "v2_single" else w), "router": None}
    return P


def evaluate(name, pol):
    route = pol["route"]
    f = lambda q: S.mach(route(q), q)  # noqa: E731
    tok_lo = sum(TOK[route(q)][q]["tok_lo"] for q in S.QIDS)
    tok_hi = sum(TOK[route(q)][q]["tok_hi"] for q in S.QIDS)
    calls = sum(TOK[route(q)][q]["calls"] for q in S.QIDS)
    rt = 0
    if pol["router"] == "glm":
        rt = sum(RQ[q]["prompt_tokens"] + RQ[q]["completion_tokens"] for q in S.QIDS)
        calls += len(S.QIDS)
    n = len(S.QIDS)
    lat = [TOK[route(q)][q]["latency_ms"] for q in S.QIDS if TOK[route(q)][q]["latency_ms"] is not None]
    lat_r = [RQ[q]["wall_ms"] for q in S.QIDS] if pol["router"] == "glm" else [0] * n
    return {"policy": name, "acc": S.by_group(f), "abstain_correct": S.acc_bounds(f, S.AB) + [len(S.AB)],
            "tokens_per_q": [round((tok_lo + rt) / n), round((tok_hi + rt) / n)], "router_tokens_per_q": round(rt / n),
            "calls_per_q": round(calls / n, 3),
            "mean_latency_s": round((sum(lat) + sum(lat_r)) / len(lat) / 1000.0, 2),
            "share_cheap": round(sum(route(q) == CHEAP for q in S.QIDS) / n, 3)}


def main():
    P = policies()
    res = {"router_test": {}, "policies": [], "comparisons": {}}
    ans = [RQ[q] for q in S.ANS]
    res["router_test"] = {
        "accuracy_answerable": [sum(r["pred"] == r["gold"] for r in ans), len(ans)],
        "confusion": {g: {p: sum(1 for r in ans if r["gold"] == g and r["pred"] == p) for p in ("T1", "T23")}
                      for g in ("T1", "T23")},
        "ab_routed_T1": sum(RQ[q]["pred"] == "T1" for q in S.AB),
        "router_tokens_total": sum(RQ[q]["prompt_tokens"] + RQ[q]["completion_tokens"] for q in S.QIDS),
        "router_cost_usd": round(sum(RQ[q]["cost_usd"] or 0 for q in S.QIDS), 6),
        "format_rule_accuracy_answerable": [sum((FMT[q] == "v2_single") == (S.tier(q) == "T1") for q in S.ANS),
                                            len(S.ANS)]}
    dev = {}
    for v in ("v1", "v2", "v3"):
        rows = [r for r in C.jl(C.S4 / ("router_dev_%s.jsonl" % v)) if r["answerable"]]
        dev[v] = {"accuracy": [sum(r["pred"] == r["gold"] for r in rows), len(rows)],
                  "T1_to_T23": sum(r["gold"] == "T1" and r["pred"] == "T23" for r in rows),
                  "T23_to_T1": sum(r["gold"] == "T23" and r["pred"] == "T1" for r in rows)}
    dq = {}
    for f in ("rpt", "book", "law"):
        for d in C.jl(C.QDIR / ("%s_dev.jsonl" % f)):
            if d["answerable"]:
                dq[d["id"]] = ((d["answer_format"] == "single"), d["tier"] == "T1")
    dev["format_rule"] = {"accuracy": [sum(a == b for a, b in dq.values()), len(dq)],
                          "T1_to_T23": sum(b and not a for a, b in dq.values()),
                          "T23_to_T1": sum(a and not b for a, b in dq.values())}
    res["router_dev"] = dev
    for name, pol in P.items():
        res["policies"].append(evaluate(name, pol))
    # paired comparisons: each routed policy vs always-<its wide arm>, vs always HYBRID_6000, vs always HR_6000
    for name, pol in P.items():
        if name.startswith("always"):
            continue
        w = [x for x in WIDE if name.endswith(x)][0]
        fr = lambda q, pol=pol: S.mach(pol["route"](q), q)  # noqa: E731
        for base in (w, CHEAP, "HR_6000"):
            fb = lambda q, b=base: S.mach(b, q)  # noqa: E731
            res["comparisons"]["%s | vs always %s" % (name, base)] = S.compare(fr, fb)
    json.dump(res, open(C.S4 / "routing_results.json", "w", encoding="utf-8"), indent=1)
    L = ["# Routing tables (generated by code/route_analysis.py from saved test verdicts/ledgers + router_test_v1.jsonl)",
         "", "Accuracy = strict machine verdicts on the 90 answerable test questions (bounds over needs_adjudication "
         "cells); tokens = query-time LLM tokens per question over all 96 (frozen per-call bound rule; router call "
         "included where used); latency = mean of saved cell latency + router wall time (descriptive).", "",
         "| Policy | All /90 | T1 /30 | T2 /30 | T3 /30 | fa /45 | en /45 | Abstain /6 | Tokens/q | Calls/q | "
         "Share to HYBRID_6000 | Mean latency s |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in res["policies"]:
        a = r["acc"]
        tk = r["tokens_per_q"]
        L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            r["policy"], S.fmt_b(a["all"]), S.fmt_b(a["T1"]), S.fmt_b(a["T2"]), S.fmt_b(a["T3"]), S.fmt_b(a["fa"]),
            S.fmt_b(a["en"]), S.fmt_b(r["abstain_correct"]), tk[0] if tk[0] == tk[1] else "%d-%d" % tuple(tk),
            r["calls_per_q"], r["share_cheap"], r["mean_latency_s"]))
    L += ["", "## Paired comparisons (90 answerable; net = wins - losses as bounds; sign p range over unresolved "
          "assignments; 95% bootstrap CI in pp over questions and over the 20 source-family components)", "",
          "| Comparison | Net | W/L (resolved) | Sign p | CI pp (questions) | CI pp (components) |", "|---|---|---|---|---|---|"]
    for k, c in res["comparisons"].items():
        L.append("| %s | %s | %d/%d | %s | [%.1f, %.1f] | [%.1f, %.1f] |" % (
            k, S.fmt_b(c["net_bounds"]), c["wins_losses_resolved"][0], c["wins_losses_resolved"][1],
            "%.3f" % c["sign_p_range"][0] if c["sign_p_range"][0] == c["sign_p_range"][1] else "%.3f-%.3f" % tuple(c["sign_p_range"]),
            c["ci_pp_question"][0], c["ci_pp_question"][1], c["ci_pp_component"][0], c["ci_pp_component"][1]))
    L += ["", "## Router", "", "Test (v1, run once): %s" % json.dumps(res["router_test"]), "",
          "Dev (54 answerable; prompt development): %s" % json.dumps(dev)]
    (C.S4 / "routing_tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
