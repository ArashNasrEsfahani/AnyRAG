"""Task 2 (review item 8): contamination sensitivity. Key contrasts on all 90, without the closed-book-correct
questions, on those questions only, and by pool. -> contam.json, contam_tables.md"""
from collections import Counter

import s7lib as L

CB = [q for q in L.ANS if L.score("CLOSEDBOOK", q) == (1, 1)]
CLEAN = [q for q in L.ANS if q not in CB]
PAIRS = [("LEX5B_6000", "HYBRID_6000"), ("LEX5B_6000", "HR_6000"), ("LEX5B_6000", "FUSION_6000"),
         ("HR_6000", "HYBRID_6000"), ("HYBRID_15500", "HYBRID_6000"), ("ITER_BM25", "HR_6000"),
         ("GOLD", "HR_6000"), ("GOLD", "LEX5B_6000"), ("GOLD", "HYBRID_15500")]
ARMS = sorted({a for p in PAIRS for a in p})
POOLS = sorted({L.pool(q) for q in L.ANS})
SETS = {"all90": L.ANS, "without_closedbook_correct": CLEAN, "closedbook_correct_only": CB}
for p in POOLS:
    SETS["pool_" + p] = [q for q in L.ANS if L.pool(q) == p]

res = {"closedbook_correct": {"n": len(CB), "by_pool": dict(Counter(L.pool(q) for q in CB)),
                              "by_tier": dict(Counter(L.tier(q) for q in CB)),
                              "by_lang": dict(Counter(L.lang(q) for q in CB)), "questions": CB},
       "accuracy": {}, "contrasts": {}}
for sn, qs in SETS.items():
    res["accuracy"][sn] = {a: list(L.total(a, qs)) for a in ARMS} | {"n": len(qs)}
    for a, b in PAIRS:
        res["contrasts"]["%s|%s vs %s" % (sn, a, b)] = L.compare(L.S(a), L.S(b), qs)
L.wjson(L.HERE / "contam.json", res)

md = ["# S7 task 2: contamination sensitivity (generated by t2_contam.py -> contam.json)", "",
      "Closed-book-correct questions (S6 CLOSEDBOOK, machine strict 1): %d of 90; by pool %s; by tier %s; by language %s." % (
          len(CB), res["closedbook_correct"]["by_pool"], res["closedbook_correct"]["by_tier"],
          res["closedbook_correct"]["by_lang"]), "",
      "## accuracy (machine strict, bounds)", "", "| set | n | " + " | ".join(ARMS) + " |",
      "|---|---|" + "---|" * len(ARMS)]
for sn in SETS:
    acc = res["accuracy"][sn]
    md.append("| %s | %d | %s |" % (sn, acc["n"], " | ".join(L.fmt(*acc[a]) for a in ARMS)))
md += ["", "## paired contrasts (net, better/worse at resolved pairs, exact sign p range, 95% bootstrap CI pp over questions / components)", ""]
for sn in ["all90", "without_closedbook_correct", "closedbook_correct_only"]:
    md += ["### " + sn, "", "| contrast | net | b/w | sign p | CI q | CI comp |", "|---|---|---|---|---|---|"]
    for a, b in PAIRS:
        c = res["contrasts"]["%s|%s vs %s" % (sn, a, b)]
        md.append("| %s vs %s | %s | %d/%d | %s | %s | %s |" % (a, b, L.fmt_net(c), *c["better_worse_resolved"],
                                                             L.fmt_p(c), L.fmt_ci(c), L.fmt_ci(c, "ci_pp_component")))
    md.append("")
md += ["### by pool (15 answerable each): net (b/w), sign p", "", "| contrast | " + " | ".join(POOLS) + " |",
       "|---|" + "---|" * len(POOLS)]
for a, b in PAIRS:
    cells = []
    for p in POOLS:
        c = res["contrasts"]["pool_%s|%s vs %s" % (p, a, b)]
        cells.append("%s (%d/%d) p %s" % (L.fmt_net(c), *c["better_worse_resolved"], L.fmt_p(c)))
    md.append("| %s vs %s | %s |" % (a, b, " | ".join(cells)))
(L.HERE / "contam_tables.md").write_text("\n".join(md) + "\n", encoding="utf-8")
print("\n".join(md))
